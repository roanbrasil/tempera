//! The report page: stylesheet and one function per section.
//!
//! Every user-provided string goes through [`escape`]; numbers go through
//! [`crate::format`], which never prints `NaN`/`inf`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use tempera_audit::{Finding, Severity};
use tempera_core::metrics::higher_is_better;
use tempera_core::spec::TaskType;
use tempera_data::eval::metric_name;

use crate::format::{self as fmt, DASH};
use crate::svg;
use crate::{ReportData, RunSummary, Winner, escape};

/// Maximum number of bars in the feature-importance chart.
const TOP_FEATURES: usize = 20;

/// Renders the complete document.
pub fn document(d: &ReportData) -> String {
    let mut out = String::with_capacity(64 * 1024);
    let _ = write!(
        out,
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <meta name=\"color-scheme\" content=\"light dark\">\n\
         <meta name=\"generator\" content=\"tempera {ver}\">\n\
         <title>{name} · tempera report</title>\n<style>{CSS}</style>\n</head>\n<body>\n<main class=\"page\">\n",
        ver = escape(&d.tempera_version),
        name = escape(&d.job_name),
    );
    header(&mut out, d);
    verdict(&mut out, d);
    leaderboard(&mut out, d);
    test_eval(&mut out, d);
    importance(&mut out, d);
    audit(&mut out, d);
    split(&mut out, d);
    reproduce(&mut out, d);
    let _ = write!(
        out,
        "<footer class=\"foot\">Generated by tempera {} · job <code>{}</code> · self-contained, works offline.</footer>\n\
         </main>\n</body>\n</html>\n",
        escape(&d.tempera_version),
        escape(&d.job_id)
    );
    out
}

fn section_open(out: &mut String, id: &str, num: u8, title: &str, lead: &str) {
    let _ = write!(
        out,
        "<section class=\"card\" id=\"{id}\"><h2><span class=\"num\">{num}</span>{title}</h2>"
    );
    if !lead.is_empty() {
        let _ = write!(out, "<p class=\"lead\">{lead}</p>");
    }
}

fn note(out: &mut String, text: &str) {
    let _ = write!(out, "<p class=\"empty\">{text}</p>");
}

fn metric_label(d: &ReportData) -> &'static str {
    fmt::metric_label(d.metric)
}

fn is_failed(r: &RunSummary) -> bool {
    r.status.eq_ignore_ascii_case("failed")
}

/// `a` is better than `b` under the main metric.
fn better(d: &ReportData, a: f64, b: f64) -> bool {
    if higher_is_better(d.metric) { a > b } else { a < b }
}

/// Index of the best scored, non-failed run.
fn best_index<'a>(d: &ReportData, runs: impl Iterator<Item = (usize, &'a RunSummary)>) -> Option<usize> {
    let mut best: Option<(usize, f64)> = None;
    for (i, r) in runs {
        let Some(s) = r.valid_score.filter(|s| s.is_finite()) else {
            continue;
        };
        if is_failed(r) {
            continue;
        }
        if best.is_none_or(|(_, b)| better(d, s, b)) {
            best = Some((i, s));
        }
    }
    best.map(|(i, _)| i)
}

fn winner_run<'a>(d: &'a ReportData, w: &Winner) -> Option<&'a RunSummary> {
    d.leaderboard.iter().find(|r| r.run_id == w.run_id).or_else(|| {
        d.leaderboard
            .iter()
            .find(|r| r.algorithm == w.algorithm && !r.is_baseline)
    })
}

fn baseline_phrase(algorithm: &str) -> String {
    let name = algorithm.replace('_', "-");
    if name.to_ascii_lowercase().contains("baseline") {
        format!("the {name}")
    } else {
        format!("the {name} baseline")
    }
}

// ---------------------------------------------------------------- 1. header

fn header(out: &mut String, d: &ReportData) {
    let ds = &d.dataset;
    let _ = writeln!(
        out,
        "<header class=\"hero\"><div class=\"temper\" aria-hidden=\"true\"></div>\
         <p class=\"eyebrow\">tempera · model report</p><h1>{name}</h1>\
         <dl class=\"meta\">\
         <div><dt>Created</dt><dd>{created}</dd></div>\
         <div><dt>Dataset</dt><dd><span class=\"wrap\">{source}</span><br><span class=\"sub\">{rows} rows × {cols} columns</span></dd></div>\
         <div><dt>Task</dt><dd>{task}<br><span class=\"sub\">main metric: {metric} ({dir})</span></dd></div>\
         <div><dt>Wall time</dt><dd>{wall}</dd></div>\
         <div><dt>Machine</dt><dd>{machine}</dd></div>\
         <div><dt>Cost</dt><dd>{cost}</dd></div>\
         </dl></header>",
        name = escape(&d.job_name),
        created = escape(&d.created_at),
        source = escape(&ds.source),
        rows = fmt::count(ds.rows),
        cols = fmt::count(ds.columns),
        task = fmt::task_label(d.task),
        metric = metric_label(d),
        dir = if higher_is_better(d.metric) {
            "higher is better"
        } else {
            "lower is better"
        },
        wall = fmt::duration(d.cost.wall_time_s),
        machine = if d.cost.machine.is_empty() {
            DASH.to_owned()
        } else {
            escape(&d.cost.machine)
        },
        cost = fmt::cost(d.cost.cost_usd),
    );
}

// ---------------------------------------------------------------- 2. verdict

fn verdict(out: &mut String, d: &ReportData) {
    let label = metric_label(d);
    match &d.winner {
        Some(w) => {
            let test = w.test.get(d.metric);
            let _ = write!(
                out,
                "<section class=\"card verdict ok\" id=\"verdict\"><h2 class=\"sr\">Verdict</h2>\
                 <p class=\"eyebrow\">Verdict · winner</p>\
                 <p class=\"winner\">{alg}</p>\
                 <div class=\"kpis\"><div class=\"kpi\"><span class=\"kpi-v\">{score}</span>\
                 <span class=\"kpi-l\">{label} on the held-out test set</span></div>",
                alg = escape(&w.algorithm),
                score = fmt::metric_opt(test),
            );
            let win_valid = winner_run(d, w)
                .and_then(|r| r.valid_score)
                .filter(|s| s.is_finite());
            let base = best_index(d, d.leaderboard.iter().enumerate().filter(|(_, r)| r.is_baseline))
                .map(|i| &d.leaderboard[i]);
            match (win_valid, base) {
                (Some(v), Some(b)) => {
                    let bs = b.valid_score.unwrap_or(f64::NAN);
                    let gain = if higher_is_better(d.metric) {
                        v - bs
                    } else {
                        bs - v
                    };
                    let phrase = if higher_is_better(d.metric) {
                        format!(
                            "{} {label} over {}",
                            fmt::signed(v - bs),
                            escape(&baseline_phrase(&b.algorithm))
                        )
                    } else {
                        format!(
                            "{} {label} vs {} (lower is better)",
                            fmt::signed(v - bs),
                            escape(&baseline_phrase(&b.algorithm))
                        )
                    };
                    let cls = if gain > 0.0 { "up" } else { "down" };
                    let _ = write!(
                        out,
                        "<div class=\"kpi\"><span class=\"kpi-v {cls}\">{}</span>\
                         <span class=\"kpi-l\">{phrase}, on validation ({} vs {})</span></div>",
                        fmt::signed(gain),
                        fmt::metric(v),
                        fmt::metric(bs)
                    );
                }
                (_, None) => {
                    let _ = write!(
                        out,
                        "<div class=\"kpi\"><span class=\"kpi-v\">{DASH}</span>\
                         <span class=\"kpi-l\">No successful baseline to compare against</span></div>"
                    );
                }
                (None, Some(_)) => {
                    let _ = write!(
                        out,
                        "<div class=\"kpi\"><span class=\"kpi-v\">{DASH}</span>\
                         <span class=\"kpi-l\">Winner has no validation score in the leaderboard</span></div>"
                    );
                }
            }
            let _ = writeln!(
                out,
                "</div><p class=\"sub\">The model was chosen on validation data; the test score above was computed once, \
                 after the choice, on {} rows it never saw.</p></section>",
                fmt::count(w.test.rows)
            );
        }
        None => {
            let failed = d.leaderboard.iter().filter(|r| is_failed(r)).count();
            let reason = if d.audit.blocked {
                let n = d.audit.blocking().count();
                format!(
                    "Training was blocked by the data audit: {n} unresolved blocking finding{}. \
                     See the Data audit section below.",
                    if n == 1 { "" } else { "s" }
                )
            } else if d.leaderboard.is_empty() {
                "No candidate was trained.".to_owned()
            } else if failed == d.leaderboard.len() {
                format!(
                    "All {} runs failed, so there is nothing to recommend. See the errors in the leaderboard.",
                    d.leaderboard.len()
                )
            } else {
                "No candidate produced a usable validation score.".to_owned()
            };
            let _ = writeln!(
                out,
                "<section class=\"card verdict none\" id=\"verdict\"><h2 class=\"sr\">Verdict</h2>\
                 <p class=\"eyebrow\">Verdict</p><p class=\"winner\">No winner</p><p>{reason}</p></section>"
            );
        }
    }
}

// ---------------------------------------------------------------- 3. leaderboard

fn leaderboard(out: &mut String, d: &ReportData) {
    let label = metric_label(d);
    section_open(
        out,
        "leaderboard",
        1,
        "Leaderboard",
        &format!("All candidates on the validation set, ranked by {label}. Baselines set the bar."),
    );
    if d.leaderboard.is_empty() {
        note(out, "No runs.");
        out.push_str("</section>\n");
        return;
    }
    let main = metric_name(d.metric);
    let others: BTreeSet<&str> = d
        .leaderboard
        .iter()
        .flat_map(|r| r.valid_metrics.keys().map(String::as_str))
        .filter(|k| *k != main)
        .collect();
    let best = best_index(d, d.leaderboard.iter().enumerate());
    let winner_id = d.winner.as_ref().map(|w| w.run_id.as_str());
    out.push_str("<div class=\"table-wrap\"><table class=\"lb\"><thead><tr><th>#</th><th>Algorithm</th><th>Backend</th>");
    let _ = write!(out, "<th class=\"n main\">{label}</th>");
    for k in &others {
        let _ = write!(out, "<th class=\"n\">{}</th>", escape(&fmt::metric_key_label(k)));
    }
    out.push_str("<th class=\"n\">Duration</th><th>Status</th></tr></thead><tbody>");
    for (i, r) in d.leaderboard.iter().enumerate() {
        let mut classes = Vec::new();
        if r.is_baseline {
            classes.push("baseline");
        }
        if is_failed(r) {
            classes.push("failed");
        }
        let _ = write!(
            out,
            "<tr class=\"{}\"><td class=\"n\">{}</td><td><strong>{}</strong>",
            classes.join(" "),
            i + 1,
            escape(&r.algorithm)
        );
        if r.is_baseline {
            out.push_str(" <span class=\"tag base\">baseline</span>");
        }
        if winner_id == Some(r.run_id.as_str()) {
            out.push_str(" <span class=\"tag win\">winner</span>");
        }
        let _ = write!(out, "</td><td>{}</td>", escape(&r.backend));
        let best_cls = if best == Some(i) { " best" } else { "" };
        let _ = write!(
            out,
            "<td class=\"n main{best_cls}\">{}</td>",
            fmt::metric_opt(r.valid_score)
        );
        for k in &others {
            let _ = write!(
                out,
                "<td class=\"n\">{}</td>",
                fmt::metric_opt(r.valid_metrics.get(*k).copied())
            );
        }
        let _ = write!(out, "<td class=\"n\">{}</td>", fmt::duration(r.duration_s));
        let status_cls = match r.status.to_ascii_lowercase().as_str() {
            "succeeded" => "s-ok",
            "failed" => "s-fail",
            _ => "s-skip",
        };
        let _ = write!(
            out,
            "<td><span class=\"status {status_cls}\">{}</span>",
            escape(&r.status)
        );
        if let Some(e) = r.error.as_deref().filter(|e| !e.is_empty()) {
            let _ = write!(out, "<div class=\"err\">{}</div>", escape(e));
        }
        out.push_str("</td></tr>");
    }
    out.push_str("</tbody></table></div>");
    let _ = writeln!(
        out,
        "<p class=\"sub\">Best validation {label} highlighted.</p></section>"
    );
}

// ---------------------------------------------------------------- 4. test evaluation

fn test_eval(out: &mut String, d: &ReportData) {
    let Some(w) = &d.winner else {
        section_open(out, "test", 2, "Test-set evaluation", "");
        note(out, "No winner, so the held-out test set was not used.");
        out.push_str("</section>\n");
        return;
    };
    let t = &w.test;
    section_open(
        out,
        "test",
        2,
        "Test-set evaluation",
        &format!(
            "<strong>{}</strong>, evaluated <strong>once</strong> on held-out test data ({} rows) that played no part \
             in training or model selection.",
            escape(&w.algorithm),
            fmt::count(t.rows)
        ),
    );
    if t.metrics.is_empty() {
        note(out, "No test metrics were recorded.");
    } else {
        let main = metric_name(d.metric);
        out.push_str("<div class=\"table-wrap narrow\"><table><thead><tr><th>Metric</th><th class=\"n\">Test</th></tr></thead><tbody>");
        let mut keys: Vec<&String> = t.metrics.keys().collect();
        keys.sort_by_key(|k| **k != main);
        for k in keys {
            let cls = if *k == main { " class=\"main-row\"" } else { "" };
            let _ = write!(
                out,
                "<tr{cls}><td>{}</td><td class=\"n\">{}</td></tr>",
                escape(&fmt::metric_key_label(k)),
                fmt::metric(t.metrics[k])
            );
        }
        out.push_str("</tbody></table></div>");
    }

    let classification = matches!(
        d.task,
        TaskType::BinaryClassification
            | TaskType::MulticlassClassification
            | TaskType::ImageClassification
            | TaskType::TextClassification
    );
    let mut charts = Vec::new();
    if classification {
        let cm = svg::confusion(
            "Confusion matrix",
            "Rows are the true class, columns the predicted class; each cell shows the count and the share of its row.",
            &t.classes,
            &t.confusion,
        );
        if cm.is_empty() {
            note(out, "No confusion matrix available.");
        } else {
            let _ = write!(
                out,
                "<h3>Confusion matrix</h3><figure class=\"fig cm\">{cm}</figure>"
            );
        }
    }
    if d.task == TaskType::BinaryClassification {
        let roc_auc = t
            .metrics
            .get("roc_auc")
            .filter(|v| v.is_finite())
            .map(|v| format!("AUC {}", fmt::metric(*v)));
        let roc = svg::curve(&svg::Curve {
            title: "ROC curve",
            desc: "True positive rate against false positive rate on the test set; the dashed diagonal is a random guess.",
            x_label: "False positive rate",
            y_label: "True positive rate",
            points: &t.roc,
            reference: svg::Reference::Diagonal,
            reference_label: "Random guess",
            annotation: roc_auc.as_deref(),
        });
        if !roc.is_empty() {
            charts.push(("ROC curve", roc, "Dashed: random guess."));
        }
        let prevalence = positive_rate(d, w);
        let pr_auc = t
            .metrics
            .get("pr_auc")
            .filter(|v| v.is_finite())
            .map(|v| format!("AP {}", fmt::metric(*v)));
        let pr = svg::curve(&svg::Curve {
            title: "Precision-recall curve",
            desc: "Precision against recall on the test set; the dashed line is the positive rate (a random guess).",
            x_label: "Recall",
            y_label: "Precision",
            points: &t.pr,
            reference: prevalence.map_or(svg::Reference::None, svg::Reference::Horizontal),
            reference_label: "Random guess (positive rate)",
            annotation: pr_auc.as_deref(),
        });
        if !pr.is_empty() {
            charts.push((
                "Precision-recall curve",
                pr,
                "Dashed: positive rate (random guess).",
            ));
        }
        if charts.is_empty() {
            note(out, "No ROC/PR curve points were recorded.");
        }
    }
    if matches!(d.task, TaskType::Regression | TaskType::TimeSeriesForecast) {
        let sc = svg::scatter(
            "Predicted vs actual",
            "Each dot is a test row (sample); dots on the dashed y = x line are perfect predictions.",
            &t.residuals,
            "Actual",
            "Predicted",
        );
        if sc.is_empty() {
            note(out, "No prediction sample was recorded.");
        } else {
            charts.push((
                "Predicted vs actual",
                sc,
                "Dashed: perfect prediction (y = x). Sample of test rows.",
            ));
        }
    }
    if !charts.is_empty() {
        out.push_str("<div class=\"charts\">");
        for (title, chart, caption) in charts {
            let _ = write!(
                out,
                "<figure class=\"fig\"><figcaption><strong>{title}</strong> · {caption}</figcaption>{chart}</figure>"
            );
        }
        out.push_str("</div>");
    }
    out.push_str("</section>\n");
}

/// Share of positives in the test set, from the confusion matrix.
fn positive_rate(d: &ReportData, w: &Winner) -> Option<f64> {
    let t = &w.test;
    if t.confusion.len() != 2 || t.classes.len() != 2 {
        return None;
    }
    let pos = d
        .split
        .positive_class
        .as_ref()
        .and_then(|p| t.classes.iter().position(|c| c == p))
        .unwrap_or(1);
    let total: u64 = t.confusion.iter().flatten().sum();
    let positives: u64 = t.confusion.get(pos)?.iter().sum();
    (total > 0).then(|| positives as f64 / total as f64)
}

// ---------------------------------------------------------------- 5. importance

fn importance(out: &mut String, d: &ReportData) {
    section_open(out, "importance", 3, "Feature importance", "");
    let items: Vec<(String, f64)> = d
        .winner
        .as_ref()
        .map(|w| {
            w.importance
                .iter()
                .filter(|(_, v)| v.is_finite())
                .take(TOP_FEATURES)
                .cloned()
                .collect()
        })
        .unwrap_or_default();
    let chart = svg::hbar(
        "Feature importance",
        "Relative importance of the winner's top features, largest first.",
        &items,
    );
    if chart.is_empty() {
        note(out, "No feature importance available for this model.");
    } else {
        let total = d.winner.as_ref().map_or(0, |w| w.importance.len());
        let _ = write!(
            out,
            "<p class=\"lead\">Top {} of {} features of the winner, largest first (scale depends on the algorithm).</p>\
             <figure class=\"fig wide\">{chart}</figure>",
            items.len(),
            total
        );
    }
    out.push_str("</section>\n");
}

// ---------------------------------------------------------------- 6. audit

fn audit(out: &mut String, d: &ReportData) {
    let a = &d.audit;
    let policy = match serde_json::to_value(a.policy) {
        Ok(serde_json::Value::String(s)) => fmt::humanize(&s),
        _ => DASH.to_owned(),
    };
    section_open(
        out,
        "audit",
        4,
        "Data audit",
        &format!(
            "Statistical checks run before training. Policy: <strong>{}</strong>. Training {}.",
            escape(&policy),
            if a.blocked {
                "<strong class=\"bad\">was blocked</strong>"
            } else {
                "was allowed"
            }
        ),
    );
    let mut by_sev: BTreeMap<std::cmp::Reverse<Severity>, Vec<&Finding>> = BTreeMap::new();
    for f in &a.findings {
        by_sev.entry(std::cmp::Reverse(f.severity)).or_default().push(f);
    }
    out.push_str("<div class=\"tally\">");
    for sev in [Severity::Red, Severity::Yellow, Severity::Green] {
        let (cls, text) = fmt::severity_badge(sev);
        let n = by_sev.get(&std::cmp::Reverse(sev)).map_or(0, Vec::len);
        let _ = write!(out, "<span class=\"badge {cls}\"><i></i>{n} {text}</span>");
    }
    out.push_str("</div>");
    if a.findings.is_empty() {
        note(out, "No findings: every check passed.");
    }
    for (sev, findings) in &by_sev {
        let (cls, text) = fmt::severity_badge(sev.0);
        let _ = write!(
            out,
            "<h3 class=\"sev-h\"><span class=\"badge {cls}\"><i></i>{text}</span></h3><ul class=\"findings\">"
        );
        for f in findings {
            let (rcls, rlabel, detail) = fmt::resolution_parts(&f.resolution);
            let _ = write!(
                out,
                "<li class=\"finding {cls}\"><div class=\"f-head\"><span class=\"f-title\">{title}</span>\
                 <span class=\"res {rcls}\">{rlabel}{detail}</span></div>\
                 <div class=\"f-id\"><code>{id}</code>{col}</div>\
                 <p><span class=\"k\">Evidence</span> {evidence}</p>\
                 <p><span class=\"k\">Suggestion</span> {suggestion}</p></li>",
                title = escape(&f.title),
                detail = detail.map(|x| format!(": {}", escape(x))).unwrap_or_default(),
                id = escape(&f.id),
                col = f
                    .column
                    .as_deref()
                    .map(|c| format!(" · column <code>{}</code>", escape(c)))
                    .unwrap_or_default(),
                evidence = escape(&f.evidence),
                suggestion = escape(&f.suggestion),
            );
        }
        out.push_str("</ul>");
    }

    out.push_str("<div class=\"cols2\"><div>");
    let _ = write!(
        out,
        "<h3>Features used ({})</h3>",
        fmt::count(a.plan.features.len() as u64 + a.plan.datetime.len() as u64)
    );
    if a.plan.features.is_empty() && a.plan.datetime.is_empty() {
        note(out, "None.");
    } else {
        out.push_str("<div class=\"table-wrap scroll-y\"><table><thead><tr><th>Name</th><th>Kind</th></tr></thead><tbody>");
        for f in &a.plan.features {
            let _ = write!(
                out,
                "<tr><td><code>{}</code></td><td>{}</td></tr>",
                escape(&f.name),
                fmt::feature_kind_label(f.kind)
            );
        }
        for c in &a.plan.datetime {
            let _ = write!(
                out,
                "<tr><td><code>{}</code></td><td>datetime → year, month, day of week, hour</td></tr>",
                escape(c)
            );
        }
        out.push_str("</tbody></table></div>");
    }
    out.push_str("</div><div>");
    let _ = write!(
        out,
        "<h3>Dropped columns ({})</h3>",
        fmt::count(a.plan.dropped.len() as u64)
    );
    if a.plan.dropped.is_empty() {
        note(out, "None.");
    } else {
        out.push_str("<div class=\"table-wrap scroll-y\"><table><thead><tr><th>Column</th><th>Reason</th></tr></thead><tbody>");
        for (c, why) in &a.plan.dropped {
            let _ = write!(
                out,
                "<tr><td><code>{}</code></td><td>{}</td></tr>",
                escape(c),
                escape(why)
            );
        }
        out.push_str("</tbody></table></div>");
    }
    out.push_str("</div></div>");
    let _ = write!(
        out,
        "<h3>Why {} with {}</h3>",
        fmt::task_label(d.task).to_lowercase(),
        metric_label(d)
    );
    if d.task_reasons.is_empty() {
        note(out, "No reasons recorded.");
    } else {
        out.push_str("<ul class=\"reasons\">");
        for r in &d.task_reasons {
            let _ = write!(out, "<li>{}</li>", escape(r));
        }
        out.push_str("</ul>");
    }
    out.push_str("</section>\n");
}

// ---------------------------------------------------------------- 7. split

fn partition_order(k: &str) -> (u8, &str) {
    let rank = match k {
        "train" => 0,
        "valid" | "validation" => 1,
        "test" => 2,
        _ => 3,
    };
    (rank, k)
}

fn split(out: &mut String, d: &ReportData) {
    let s = &d.split;
    section_open(out, "split", 5, "Split", "");
    let _ = write!(
        out,
        "<dl class=\"facts\"><div><dt>Strategy</dt><dd>{}</dd></div><div><dt>Seed</dt><dd><code>{}</code></dd></div>\
         <div><dt>Removed: null target</dt><dd>{}</dd></div><div><dt>Removed: duplicates</dt><dd>{}</dd></div>",
        fmt::strategy_label(s.strategy),
        s.seed,
        fmt::count(s.dropped_null_target),
        fmt::count(s.dropped_duplicates),
    );
    if let Some(p) = &s.positive_class {
        let _ = write!(
            out,
            "<div><dt>Positive class</dt><dd><code>{}</code></dd></div>",
            escape(p)
        );
    }
    out.push_str("</dl>");

    let mut parts: Vec<&String> = s.rows.keys().chain(s.class_counts.keys()).collect();
    parts.sort_by_key(|k| partition_order(k));
    parts.dedup();
    if parts.is_empty() {
        note(out, "No partition sizes recorded.");
        out.push_str("</section>\n");
        return;
    }
    let total: u64 = s.rows.values().sum();
    let classes: Vec<&String> = if s.classes.is_empty() {
        s.class_counts
            .values()
            .flat_map(|m| m.keys())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect()
    } else {
        s.classes.iter().collect()
    };
    out.push_str("<div class=\"table-wrap\"><table><thead><tr><th></th>");
    for p in &parts {
        let _ = write!(out, "<th class=\"n\">{}</th>", escape(&fmt::humanize(p)));
    }
    out.push_str("<th class=\"n\">Total</th></tr></thead><tbody><tr class=\"main-row\"><td>Rows</td>");
    for p in &parts {
        let n = s.rows.get(*p).copied().unwrap_or(0);
        let share = if total > 0 {
            format!(
                " <span class=\"sub\">{}</span>",
                fmt::percent(n as f64 / total as f64)
            )
        } else {
            String::new()
        };
        let _ = write!(out, "<td class=\"n\">{}{share}</td>", fmt::count(n));
    }
    let _ = write!(out, "<td class=\"n\">{}</td></tr>", fmt::count(total));
    for c in &classes {
        let _ = write!(out, "<tr><td>Class <code>{}</code></td>", escape(c));
        let mut row_total = 0;
        for p in &parts {
            let n = s
                .class_counts
                .get(*p)
                .and_then(|m| m.get(*c))
                .copied()
                .unwrap_or(0);
            row_total += n;
            let _ = write!(out, "<td class=\"n\">{}</td>", fmt::count(n));
        }
        let _ = write!(out, "<td class=\"n\">{}</td></tr>", fmt::count(row_total));
    }
    out.push_str("</tbody></table></div></section>\n");
}

// ---------------------------------------------------------------- 8. reproduce

fn reproduce(out: &mut String, d: &ReportData) {
    section_open(
        out,
        "reproduce",
        6,
        "Reproduce",
        "The exact spec and command that produced this report (same data hash and seed give the same split).",
    );
    let cmd = if d.reproduce_command.is_empty() {
        DASH.to_owned()
    } else {
        escape(&d.reproduce_command)
    };
    let _ = write!(
        out,
        "<h3>Command</h3><pre class=\"code cmd\"><code>{cmd}</code></pre>"
    );
    let _ = write!(out, "<h3>tempera.yaml</h3>");
    if d.spec_yaml.trim().is_empty() {
        note(out, "Spec not recorded.");
    } else {
        let _ = write!(
            out,
            "<pre class=\"code\"><code>{}</code></pre>",
            escape(d.spec_yaml.trim_end())
        );
    }
    out.push_str("<h3>Artifacts</h3>");
    match d.winner.as_ref().filter(|w| !w.artifacts.is_empty()) {
        Some(w) => {
            out.push_str("<div class=\"table-wrap\"><table><thead><tr><th>Format</th><th>Path</th></tr></thead><tbody>");
            for (format, path) in &w.artifacts {
                let _ = write!(
                    out,
                    "<tr><td>{}</td><td><code class=\"wrap\">{}</code></td></tr>",
                    escape(format),
                    escape(path)
                );
            }
            out.push_str("</tbody></table></div>");
        }
        None => note(out, "No model artifacts were exported."),
    }
    out.push_str("</section>\n");
}

